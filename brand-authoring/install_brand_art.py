"""Render original vector study B into app resources. No legacy image is an input."""
from pathlib import Path
import hashlib,importlib.util,io,json
from PIL import Image
R=Path(__file__).resolve().parent;S=R.parent/'source'
spec=importlib.util.spec_from_file_location('original_trackwerk_geometry',R/'build_studies.py');art=importlib.util.module_from_spec(spec);spec.loader.exec_module(art)
written=[]
def save(path,data):
 path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data);written.append(dict(path=str(path.relative_to(S)),sha256=hashlib.sha256(data).hexdigest(),bytes=len(data)))
def png(size):
 scene=art.Scene(size,size,art.CONCEPTS['B']['bg']);art.mark(scene,'B',0,0,size)
 o=io.BytesIO();scene.im.resize((size,size),Image.Resampling.LANCZOS).save(o,format='PNG');return o.getvalue()
for density,size in [('mdpi',48),('hdpi',72),('xhdpi',96),('xxhdpi',144),('xxxhdpi',192)]:
 for name in ['ic_launcher.png','ic_launcher_round.png']:save(S/f'app/src/main/res/mipmap-{density}/{name}',png(size))
for density,size in [('mdpi',288),('hdpi',432),('xhdpi',576),('xxhdpi',864)]:
 save(S/f'app/src/main/res/drawable-{density}/ic_splash_logo.png',png(size))
geometry=art.geometry('B')
def vector(mono):
 paths=[]
 for layer,op,args in geometry:
  assert op=='poly';points=[(29+x*1.6,27+y*1.6) for x,y in args]
  data='M'+'L'.join(f'{x:g},{y:g}' for x,y in points)+'Z'
  color='#FFFFFFFF' if mono else '#63E7EF' if layer=='main' else '#EF61CE'
  paths.append(f'    <path android:pathData="{data}" android:fillColor="{color}" />')
 return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Original TrackWerk TW geometry / GPL-3.0-or-later. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'+'\n'.join(paths)+'\n</vector>\n').encode()
save(S/'app/src/main/res/drawable/ic_launcher_foreground.xml',vector(False));save(S/'app/src/main/res/drawable/ic_launcher_monochrome.xml',vector(True))
save(S/'app/src/main/res/drawable/ic_launcher_background.xml',b'<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108"><path android:pathData="M0,0H108V108H0Z" android:fillColor="#0B0D20"/><path android:pathData="M0,18H108M0,36H108M0,54H108M0,72H108M0,90H108" android:strokeColor="#1B2031" android:strokeWidth="0.4" android:fillColor="#00000000"/></vector>\n')
save(S/'app/src/main/res/values/ic_launcher_background.xml',b'<?xml version="1.0" encoding="utf-8"?>\n<resources><color name="ic_launcher_background">#0B0D20</color></resources>\n')
data=png(128);header='// Generated by brand-authoring/install_brand_art.py from original TrackWerk vector geometry.\n#pragma once\nstatic const unsigned char kWindowIconPng[]={\n'
for i in range(0,len(data),16):header+='    '+','.join(f'0x{v:02x}' for v in data[i:i+16])+',\n'
header+='};\nstatic constexpr unsigned int kWindowIconPngLen=sizeof(kWindowIconPng);\n';save(S/'shell/sdl/window_icon.h',header.encode())
save(S/'docs/images/trackwerk-app.png',png(256))
(R/'NATIVE-BRAND-ASSETS.json').write_text(json.dumps(dict(original_vector_source='TrackWerk B / Raster Cracktro',identity_and_storage_unchanged=True,assets=written),indent=2)+'\n');print('Rendered',len(written),'app resources from original geometry.')
