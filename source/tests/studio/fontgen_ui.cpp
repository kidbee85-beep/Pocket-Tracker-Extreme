// macOS generator for the embedded proportional interface font.
// clang++ -std=c++17 -O2 tests/studio/fontgen_ui.cpp -framework CoreText \
//   -framework CoreGraphics -framework CoreFoundation -o fontgen-ui
// ./fontgen-ui app/src/main/assets/fonts/LiberationSans-Regular.ttf > native/ui/font_ui.h
// Liberation font copyright and SIL OFL-1.1 ship in docs/licenses/.
#include <CoreText/CoreText.h>
#include <CoreGraphics/CoreGraphics.h>
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <vector>

namespace {
struct Raster {
    std::array<unsigned char, 64 * 64> ink{};
    int top = 64, bottom = 0, left = 64, right = 0, advance = 0;
    bool empty() const { return right <= left || bottom <= top; }
};

Raster raster(CTFontRef font, uint32_t cp) {
    Raster result;
    auto space = CGColorSpaceCreateDeviceGray();
    auto context = CGBitmapContextCreate(result.ink.data(), 64, 64, 8, 64, space, kCGImageAlphaNone);
    CGColorSpaceRelease(space);
    if (!context) return result;
    CGContextSetGrayFillColor(context, 1, 1);
    CGContextSetAllowsFontSmoothing(context, false);
    CGContextSetShouldSmoothFonts(context, false);
    CGContextSetShouldAntialias(context, true);
    CGContextSetShouldSubpixelPositionFonts(context, false);
    UniChar character = static_cast<UniChar>(cp);
    CGGlyph glyph = 0;
    CTFontGetGlyphsForCharacters(font, &character, &glyph, 1);
    CGSize advance{};
    CTFontGetAdvancesForGlyphs(font, kCTFontOrientationHorizontal, &glyph, &advance, 1);
    result.advance = std::max(1, static_cast<int>(std::lround(advance.width)));
    CGPoint pos = {16, 20};
    CTFontDrawGlyphs(font, &glyph, &pos, 1, context);
    CGContextRelease(context);
    for (int y = 0; y < 64; ++y) for (int x = 0; x < 64; ++x) {
        if (result.ink[y * 64 + x] < 8) { result.ink[y * 64 + x] = 0; continue; }
        result.left = std::min(result.left, x); result.right = std::max(result.right, x + 1);
        result.top = std::min(result.top, y); result.bottom = std::max(result.bottom, y + 1);
    }
    return result;
}
}

int main(int argc, char** argv) {
    if (argc != 2) { std::fprintf(stderr, "usage: fontgen-ui LiberationSans-Regular.ttf\n"); return 1; }
    std::ifstream input(argv[1], std::ios::binary);
    std::vector<unsigned char> bytes((std::istreambuf_iterator<char>(input)), {});
    if (bytes.empty()) return 2;
    auto provider = CGDataProviderCreateWithData(nullptr, bytes.data(), bytes.size(), nullptr);
    auto graphics = CGFontCreateWithDataProvider(provider);
    CGDataProviderRelease(provider);
    if (!graphics) return 3;
    std::vector<uint32_t> characters;
    for (uint32_t cp = 32; cp < 127; ++cp) characters.push_back(cp);
    for (uint32_t cp = 160; cp < 256; ++cp) characters.push_back(cp);
    characters.push_back(0x2026);
    std::puts("// Liberation Sans Regular (SIL OFL-1.1), grayscale proportional UI raster.\n"
              "// Generated by tests/studio/fontgen_ui.cpp; TTF in app/src/main/assets/fonts.\n"
              "#pragma once\n#include <cstdint>\nnamespace pt::ui::detail {\n"
              "struct UiFontGlyph { uint32_t offset; uint8_t width, left, advance; };\n");
    for (int size : {12, 18}) {
        const int height = size == 12 ? 14 : 21;
        CTFontRef font = nullptr;
        std::vector<Raster> glyphs;
        int top = 64, bottom = 0;
        for (float em = static_cast<float>(size); em > 5; em -= .05f) {
            if (font) CFRelease(font);
            font = CTFontCreateWithGraphicsFont(graphics, em, nullptr, nullptr);
            glyphs.clear(); top = 64; bottom = 0;
            for (auto cp : characters) {
                auto g = raster(font, cp);
                if (!g.empty()) { top = std::min(top, g.top); bottom = std::max(bottom, g.bottom); }
                glyphs.push_back(g);
            }
            if (bottom - top <= height) break;
        }
        std::fprintf(stderr, "UI%d: em %.2f, full Latin-1 ink height %d/%d\n", size, CTFontGetSize(font), bottom - top, height);
        struct Record { unsigned offset, width, left, advance; };
        std::vector<Record> records;
        std::vector<unsigned> pixels;
        const int ypad = (height - (bottom - top)) / 2;
        for (const auto& g : glyphs) {
            const int width = g.empty() ? 0 : g.right - g.left;
            const int left = g.empty() ? 0 : std::max(0, g.left - 16);
            records.push_back({static_cast<unsigned>(pixels.size()), static_cast<unsigned>(width),
                               static_cast<unsigned>(left), static_cast<unsigned>(std::max(g.advance, left + width))});
            for (int y = 0; y < height; ++y) for (int x = 0; x < width; ++x) {
                const int sy = y - ypad + top;
                unsigned alpha = sy >= g.top && sy < g.bottom ? g.ink[sy * 64 + g.left + x] : 0;
                // A modest gamma lift keeps 12px labels readable without LCD colour fringes.
                pixels.push_back(alpha ? static_cast<unsigned>(std::lround(std::pow(alpha / 255., .82) * 255.)) : 0);
            }
        }
        std::printf("inline constexpr int uiFont%dHeight=%d;\n", size, height);
        std::printf("inline constexpr UiFontGlyph uiFont%dGlyphs[%zu]={\n", size, records.size());
        for (const auto& record : records)
            std::printf("{%u,%u,%u,%u},\n", record.offset, record.width, record.left, record.advance);
        std::puts("};");
        std::printf("inline constexpr uint8_t uiFont%dPixels[%zu]={\n", size, pixels.size());
        for (size_t i = 0; i < pixels.size(); ++i) { std::printf("%u,", pixels[i]); if (i % 48 == 47) std::putchar('\n'); }
        std::puts("\n};");
        CFRelease(font);
    }
    std::puts("} // namespace pt::ui::detail");
    CGFontRelease(graphics);
}
